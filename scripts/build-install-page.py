#!/usr/bin/env python3
"""Build a one-click install page for the Aliento signature.

Leroy: "are we able to set this up for my sister?"

The honest answer shapes this file. A signature is not a server-side setting — it lives in whichever mail client
she sends from — so nobody can install it *for* her remotely. What can be removed is every step around it: this
page shows the card, copies it to the clipboard as rich HTML with one button (which is the only reliable way to
move a signature from a browser into a mail client), and carries the three sets of client instructions she is
actually likely to need.

Built from the same email file that ships, so the page cannot offer a signature the emails do not contain.
"""

import re
from pathlib import Path

D = Path("/root/aliento-nextjs/email-signature")
OUT = D / "aliento-install.html"
FULL = D / "aliento-signature-full.html"


def fragment() -> str:
    html = FULL.read_text()
    start = html.find("<!-- paste from here")
    end = html.find("<!-- to here")
    assert start != -1 and end != -1, "paste markers missing"
    frag = html[start:end].replace("<!-- paste from here ------------------------------------------------------->", "")
    without_comments = re.sub(r"<!--.*?-->", "", frag, flags=re.S)
    assert not re.search(r"<style[\s>]", without_comments, re.I), "a <style> element is inside the paste region"
    assert "sig-card" in frag and "leegale@alientomd.com" in frag, "the card did not extract as expected"
    return frag.strip()


def main() -> None:
    card = fragment()
    # the copy button needs the markup as a JS string: escape backticks and backslashes only
    card_js = card.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")

    page = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Aliento — install your email signature</title>
<!--
  GENERATED by scripts/build-install-page.py from aliento-signature-full.html. Do not edit by hand.

  Why a page and not an attachment: a signature has to arrive in a mail client's signature editor as RICH HTML.
  Pasting the source into a text box gives raw angle brackets, and pasting a screenshot gives an image nobody can
  select. Copying the rendered block from a browser is the one path that preserves the formatting, so this page
  exists to make that one action a single button.
-->
<style>
  :root { --cream:#FEFCF8; --card:#FDF8F0; --line:#E5E1DB; --ink:#2E2A26; --body:#433E34; --muted:#635B4E; --sage:#3A5746; }
  * { box-sizing: border-box; }
  body {
    margin:0; padding:32px 20px 72px; background:var(--cream); color:var(--body);
    font-family:-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif; line-height:1.65;
  }
  .wrap { max-width: 680px; margin: 0 auto; }
  h1 { font-family:'Instrument Serif',Georgia,serif; font-weight:400; font-size:34px; margin:0 0 6px; color:var(--ink); }
  .lede { margin:0 0 26px; font-size:15px; color:var(--muted); }
  .stage { background:var(--card); border:1px solid var(--line); border-radius:6px; padding:26px; margin:0 0 14px; }
  .row { display:flex; gap:10px; flex-wrap:wrap; align-items:center; margin:0 0 30px; }
  button.copy {
    font:inherit; font-size:14px; font-weight:700; letter-spacing:.2px;
    background:var(--sage); color:#fff; border:0; border-radius:999px; padding:13px 26px; cursor:pointer;
  }
  button.copy:active { transform: translateY(1px); }
  .status { font-size:13px; color:var(--sage); font-weight:600; }
  .status.err { color:#9E4A38; }
  h2 { font-size:12px; letter-spacing:1.4px; text-transform:uppercase; color:var(--muted); margin:34px 0 10px; }
  ol { padding-left:22px; margin:0 0 14px; }
  li { margin:0 0 8px; }
  code { background:#F3F1ED; padding:1px 5px; border-radius:3px; font-size:13px; }
  .note { font-size:13px; color:var(--muted); border-left:2px solid var(--line); padding-left:14px; margin:14px 0 0; }
  #holder { position:absolute; left:-9999px; top:0; }
</style>
</head>
<body>
<div class="wrap">
  <h1>Your Aliento signature</h1>
  <p class="lede">One button below puts the signature on your clipboard as formatted content. Then paste it into
  your mail app's signature box — not into a new message. It takes about a minute.</p>

  <div class="stage" id="stage">__CARD__</div>

  <div class="row">
    <button class="copy" id="copyBtn" type="button">Copy signature</button>
    <span class="status" id="status"></span>
  </div>

  <h2>Gmail — computer</h2>
  <ol>
    <li>Click <strong>Copy signature</strong> above.</li>
    <li>In Gmail, open <strong>Settings</strong> (the gear) → <strong>See all settings</strong> → <strong>General</strong>.</li>
    <li>Scroll to <strong>Signature</strong> → <strong>Create new</strong>, name it <code>Aliento</code>.</li>
    <li>Click into the signature box and paste (<code>Ctrl+V</code> / <code>⌘V</code>).</li>
    <li>Scroll to the bottom and <strong>Save Changes</strong>.</li>
    <li>Under <strong>Signature defaults</strong>, set it for <strong>New mail</strong> and for
        <strong>On reply/forward</strong> use <code>—</code> so replies do not repeat the full card.</li>
  </ol>

  <h2>Gmail — phone</h2>
  <ol>
    <li>The Gmail app cannot paste a formatted signature. Set it once on a computer; it then applies on the phone too.</li>
  </ol>

  <h2>Outlook — desktop</h2>
  <ol>
    <li>Click <strong>Copy signature</strong> above.</li>
    <li><strong>File</strong> → <strong>Options</strong> → <strong>Mail</strong> → <strong>Signatures…</strong></li>
    <li><strong>New</strong>, name it, then paste into the box and click <strong>OK</strong>.</li>
    <li>Set it as the default for New messages and Replies/forwards.</li>
  </ol>

  <h2>Outlook — web, or Apple Mail</h2>
  <ol>
    <li>Click <strong>Copy signature</strong> above.</li>
    <li><strong>Outlook web:</strong> Settings → Mail → Compose and reply → paste into the signature box → Save.</li>
    <li><strong>Apple Mail:</strong> Mail → Settings → Signatures → choose the account → <strong>+</strong> → paste →
        untick <em>Always match my default message font</em>.</li>
  </ol>

  <h2>If it pastes as plain text</h2>
  <p class="note">Use the button on a computer browser, not a phone. If the formatting still drops, open the
  signature file itself in a browser and select the card with the mouse before copying — some browsers refuse to
  put rich content on the clipboard when the tab is not focused.</p>

  <p class="note">The card is built so that a mail client which strips styling still shows the correct light
  version, with the name, title and contact details as real text — so it stays selectable and searchable. The dark
  version switches by itself in Apple Mail and in HTML mail that is sent, rather than pasted.</p>
</div>

<div id="holder"></div>

<script>
  var CARD_HTML = `__CARD_JS__`;

  function setStatus(msg, isErr) {
    var el = document.getElementById('status');
    el.textContent = msg;
    el.className = 'status' + (isErr ? ' err' : '');
  }

  // Clipboard write with rich HTML: this is what carries the formatting into a mail client's signature editor.
  function copyRich() {
    if (!navigator.clipboard || !window.ClipboardItem) return Promise.reject(new Error('no clipboard api'));
    var item = new ClipboardItem({
      'text/html': new Blob([CARD_HTML], { type: 'text/html' }),
      'text/plain': new Blob([document.getElementById('stage').innerText], { type: 'text/plain' })
    });
    return navigator.clipboard.write([item]);
  }

  // Fallback: select the rendered card and let the browser copy the DOM, which also preserves formatting.
  function copySelection() {
    var stage = document.getElementById('stage');
    var range = document.createRange();
    range.selectNodeContents(stage);
    var sel = window.getSelection();
    sel.removeAllRanges();
    sel.addRange(range);
    var ok = document.execCommand('copy');
    sel.removeAllRanges();
    if (!ok) throw new Error('execCommand refused');
  }

  document.getElementById('copyBtn').addEventListener('click', function () {
    setStatus('Copying…');
    copyRich().then(function () {
      setStatus('Copied — now paste it into your signature box.');
    }).catch(function () {
      try {
        copySelection();
        setStatus('Copied — now paste it into your signature box.');
      } catch (e) {
        setStatus('Could not copy automatically. Select the card above with your mouse and press Ctrl/Cmd+C.', true);
      }
    });
  });
</script>
</body>
</html>
"""
    page = page.replace("__CARD__", card).replace("__CARD_JS__", card_js)
    OUT.write_text(page)

    # the page must actually contain the whole card, and the copy payload must be non-trivial
    text = OUT.read_text()
    for needle, label in [("leegale@alientomd.com", "email"), ("076 236 7921", "phone"),
                          ("alientomd.com</a>", "website"), ("Dr Leegale Franscesca Adonis", "name"),
                          ("Public Health Medicine Specialist", "title")]:
        assert needle in text, f"install page is missing the {label}"
    assert text.count("sig-card") >= 2, "the card appears in both the preview and the copy payload"
    assert "<script>document.write" not in text
    print(f"  {OUT.name}  {OUT.stat().st_size} bytes  card {len(card)} chars")


if __name__ == "__main__":
    main()
